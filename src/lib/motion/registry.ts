import type { DurToken, EaseToken } from "./tokens";

/**
 * The motion effect registry (docs plan Appendix A). Every effect the site uses is declared here with
 * a trigger, a meaning, the tokens it uses, how each tier runs it and what it becomes under reduced
 * motion. `tests/unit/motion-registry.test.ts` fails on any gap, and the Motion lab renders this list,
 * so an effect cannot ship without a documented reduced variant.
 *
 * This module is data only: nothing on the public bundle imports it.
 */

export type Meaning = "transmit" | "resolve" | "assemble" | "respond";

/** How a tier runs an effect: `run` scripted, `css` the CSS-only variant, `none` not at all. */
export type TierSupport = "run" | "css" | "none";

export type EffectTiers = Readonly<{
  t3: TierSupport;
  t2: TierSupport;
  t1: TierSupport;
}>;

export type MotionEffect = Readonly<{
  id: string;
  surface: "public" | "console";
  name: string;
  trigger: string;
  /** Console effects carry no meaning of their own (calm preset). */
  meaning?: Meaning;
  /** Timing as the plan prints it, for display. */
  timing: string;
  durations: readonly DurToken[];
  eases: readonly EaseToken[];
  /** Public effects only; the console is CSS-only and renders the same everywhere. */
  tiers?: EffectTiers;
  /** What the viewer gets under reduced motion (or off). */
  reduced: string;
  /** The phase that builds it. */
  phase: number;
  built: boolean;
  /** Repo-relative file that implements it, once built. */
  implementation?: string;
}>;

const tiers = (t3: TierSupport, t2: TierSupport, t1: TierSupport) => ({
  t3,
  t2,
  t1,
});

